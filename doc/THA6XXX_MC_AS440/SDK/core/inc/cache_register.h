/*SCTLR Register*/
#define SCTLR_D_CACHE_POS 2U
#define SCTLR_D_CACHE_MASK (1UL << SCTLR_D_CACHE_POS)

#define SCTLR_I_CACHE_POS 12U
#define SCTLR_I_CACHE_MASK (1UL << SCTLR_I_CACHE_POS)

/*CCSIDR Register*/
#define CCSIDR_NUMSETS_POS 13U
#define CCSIDR_NUMSETS_MASK (0x7FFFUL << CCSIDR_NUMSETS_POS)

#define CCSIDR_ASSOCIATIVITY_POS 3U
#define CCSIDR_ASSOCIATIVITY_MASK (0x3FFUL << CCSIDR_ASSOCIATIVITY_POS)

/*DCISW Register*/
#define DCISW_WAY_POS 30U
#define DCISW_WAY_MASK (3UL << DCISW_WAY_POS)

#define DCISW_SET_POS 6U
#define DCISW_SET_MASK (0x7FUL << DCISW_SET_POS)

/*DCCSW Register*/
#define DCCSW_WAY_POS 30U
#define DCCSW_WAY_MASK (3UL << DCCSW_WAY_POS)

#define DCCSW_SET_POS 6U
#define DCCSW_SET_MASK (0x7FUL << DCCSW_SET_POS)

