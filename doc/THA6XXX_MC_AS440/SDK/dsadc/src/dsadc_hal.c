boolean Dsadc_Hal_InitModule(DSADC_MODULE *const pDsadc, const Dsadc_ModuleConfig *const pConfig)
{
    boolean ret = TRUE;
    
#if(INPUT_ARG_DETECT == STD_ON)
    /*Check if the pDsadc is null pointer*/
    /* #Violation: dsadc_hal_c_REF_1 */
    /* #Violation: dsadc_hal_c_REF_2 */
    Assert((boolean)(CHECK_DSADC_BASE(pDsadc)));
    /*Check if the pConfig is null pointer*/
    /* #Violation: dsadc_hal_c_REF_2 */
    Assert((boolean)(NULL_PTR != pConfig ));
#endif
    if(NULL_PTR != pConfig->pModulatorConfig)
    {
        /*Config modulator function*/
        ret &= Dsadc_Std_ConfigModulator(pDsadc,pConfig->pModulatorConfig);
    }

    if(NULL_PTR != pConfig->pDemodulatorConfig)
    {
        /*Config demodulator function*/
        ret &= Dsadc_Std_ConfigDemodulator(pDsadc,pConfig->pDemodulatorConfig);
    }

    if(NULL_PTR != pConfig->pTimeStampConfig)
    {
        /*Config Time-stamp function*/
        ret &= Dsadc_Std_ConfigTimeStamp(pDsadc,pConfig->pTimeStampConfig);
    }

    if(NULL_PTR != pConfig->pMainFilterConfig)
    {
        /*Config main filter function*/
        ret &= Dsadc_Std_ConfigMainFilter(pDsadc,pConfig->pMainFilterConfig);
    }

    if(NULL_PTR != pConfig->pAuxiliaryFilterConfig)
    {
        /*Config Auxiliary filter function*/
        ret &= Dsadc_Std_ConfigAuxFilter(pDsadc,pConfig->pAuxiliaryFilterConfig);
    }

    if(NULL_PTR != pConfig->pThresholdConfig)
    {
        /*Config threshold function*/
        ret &= Dsadc_Std_ConfigThreshold(pDsadc,pConfig->pThresholdConfig);
    }

    if(NULL_PTR != pConfig->pMeanConfig)
    {
        /*Config mean function*/
        ret &= Dsadc_Std_ConfigMean(pDsadc,pConfig->pMeanConfig);
    }


    if(NULL_PTR != pConfig->pFifoConfig)
    {
        /*Config FIFO function*/
        ret &= Dsadc_Std_ConfigFifo(pDsadc,pConfig->pFifoConfig);
    }
    else
    {
        pDsadc->DEMICFG.B.FIFOBYPASS = 1U;
        ret = Dsadc_Register_ReadBack_Check(ret, 1U, pDsadc->DEMICFG.B.FIFOBYPASS);
    }
    return ret;
}

