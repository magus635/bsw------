/* #Violation: dsadc_hal_c_REF_18 */
boolean Dsadc_Hal_ConfigBiasVoltage(DSADC_MODULE *const pDsadc , Dsadc_BiasVoltageSelect voltage , boolean enable)
{
    boolean ret;
    uint8 comVoSpbBypassVal;
    /* #Violation: dsadc_hal_c_REF_5 */
    DSADC_MODCFG modCfgValue;
    uint16 channelCfg;

#if(INPUT_ARG_DETECT == STD_ON)
    /*Check if the pDsadc is null pointer*/
    /* #Violation: dsadc_hal_c_REF_1 */
    /* #Violation: dsadc_hal_c_REF_2 */
    Assert((boolean)(CHECK_DSADC_BASE(pDsadc)));
#endif

    ret = TRUE;

    if (TRUE == enable)
    {
        comVoSpbBypassVal = 0U;
    }
    else
    {
        comVoSpbBypassVal = 1U;
    }

    /* Enable Bias Voltage*/
    pDsadc->COMPCON.B.CALEN = 0U;
    ret = Dsadc_Register_ReadBack_Check(ret, 0U, pDsadc->COMPCON.B.CALEN);

    pDsadc->COMPCON.B.VSELLV = (uint32)voltage;
    ret = Dsadc_Register_ReadBack_Check(ret, (uint32)voltage, pDsadc->COMPCON.B.VSELLV);

    /*
                        DSADC Input Channel Configuration
        Mode               PINSET   NINSET   PINEN   NINEN      INPSEL  |   MODCFG&0xF  | INPSEL<<8 |  channelCfg
        Single Negative B  0        1        0       1          0       |       0xA     |     0     |     0xA    
        Single Negative A  0        1        0       1          1       |       0xA     |   0x100   |     0x10A   
        Single Positive B  1        0        1       0          0       |       0x5     |     0     |     0x5    
        Single Positive A  1        0        1       0          1       |       0x5     |   0x100   |     0x105    
        Differential B     1        1        1       1          0       |       0xF     |     0     |     0xF   
        Differential A     1        1        1       1          1       |       0xF     |   0x100   |     0x10F
    */
    
    modCfgValue.U = pDsadc->MODCFG.U;
    channelCfg = (uint16)(modCfgValue.U & 0x10FU);
    
    /* Config Bias Voltage source*/
    switch (channelCfg)
    { 
        case 0x105U:
            {
                /* Config SPA*/
                pDsadc->MODCFG.B.INPWP = 1U;
                pDsadc->MODCFG.B.COMVOSPAEN = enable;
                ret = Dsadc_Register_ReadBack_Check(ret, enable, pDsadc->MODCFG.B.COMVOSPAEN);
                pDsadc->MODCFG.B.INPWP = 0U;
            }
            break;
        case 0x10AU:
            {
                /* Config SNA*/
                pDsadc->CPVCFG.B.VXEN = 1U;
                pDsadc->CPVCFG.B.COMVOSNAEN = enable;
                ret = Dsadc_Register_ReadBack_Check(ret, (uint32)enable, pDsadc->CPVCFG.B.COMVOSNAEN);
            }
            break;
        case 0x5U:
            {
                /* Config SPB*/
                pDsadc->MFCFG.B.COMVOSPBBYPASS = comVoSpbBypassVal;
                ret = Dsadc_Register_ReadBack_Check(ret, comVoSpbBypassVal, pDsadc->MFCFG.B.COMVOSPBBYPASS);       
            }
            break;

        case 0xAU:
            {
                /* Config SNB*/
                pDsadc->CPVCFG.B.VXEN = 1U;
                pDsadc->CPVCFG.B.COMVOSNBEN = enable;
                ret = Dsadc_Register_ReadBack_Check(ret, (uint32)enable, pDsadc->CPVCFG.B.COMVOSNBEN);
            }
            break;

        case 0x10FU:
            {
                /* Config SPA and SNA*/
                pDsadc->MODCFG.B.INPWP = 1U;
                pDsadc->MODCFG.B.COMVOSPAEN = enable;
                ret = Dsadc_Register_ReadBack_Check(ret, (uint32)enable, pDsadc->MODCFG.B.COMVOSPAEN);
                pDsadc->MODCFG.B.INPWP = 0U;
                pDsadc->CPVCFG.B.VXEN = 1U;
                pDsadc->CPVCFG.B.COMVOSNAEN = enable;
                ret = Dsadc_Register_ReadBack_Check(ret, (uint32)enable, pDsadc->CPVCFG.B.COMVOSNAEN);
            }
            break;

        case 0xFU:
            {
                /* Config SPB and SNB*/
                pDsadc->MFCFG.B.COMVOSPBBYPASS = comVoSpbBypassVal;
                ret = Dsadc_Register_ReadBack_Check(ret, comVoSpbBypassVal, pDsadc->MFCFG.B.COMVOSPBBYPASS);
        
                pDsadc->CPVCFG.B.VXEN = 1U;
                pDsadc->CPVCFG.B.COMVOSNBEN = enable;
                ret = Dsadc_Register_ReadBack_Check(ret, (uint32)enable, pDsadc->CPVCFG.B.COMVOSNBEN);
            }
            break;
        default:
            /* #Violation: dsadc_hal_c_REF_17 */
            ret = FALSE;
            break;
    }

    return ret;
}

