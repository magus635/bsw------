#define STM_TICKS_MS  25000UL

void Timer_DelayMs(uint32 DelayMs)
{
    volatile uint64 Stm_value;
    volatile uint64 Marker;
    uint64 Target;
    /* Get current tick */
    Marker = Stm_Hal_GetValue(); /* Get system counter */
    Target = (uint64)DelayMs * (uint64)STM_TICKS_MS + Marker;
    do
    {
        Stm_value = Stm_Hal_GetValue(); /* Get system counter */
    } while (Stm_value < Target);
}
