"""Pure-Python dataclasses backing the Communication Configuration Workbench."""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional


@dataclass
class CommChannelRow:
    """Aggregated physical/network communication channel across ComM/CanSM/CanIf/Can/CanTrcv."""

    channel_name: str
    bus_type: str = "CAN"
    comm_channel_id: Optional[int] = None
    nm_variant: str = "-"
    cansm_network_name: str = ""
    canif_ctrl_name: str = ""
    can_controller_name: str = ""
    hardware_channel: str = ""
    baudrate_kbps: Optional[float] = None
    fd_baudrate_kbps: Optional[float] = None
    rx_processing: str = ""
    tx_processing: str = ""
    trcv_channel_name: str = ""
    trcv_init_state: str = ""
    trcv_max_baudrate: Optional[int] = None
    has_broken_link: bool = False
    primary_container_path: str = ""


@dataclass
class CommMessageRow:
    """End-to-end CAN/TP message chain spanning Com, PduR, CanIf, CanTp, and EcuC."""

    direction: str  # "TX" | "RX"
    category: str  # "COM" | "DIAG_TP" | "ORPHAN"
    name: str
    can_id: Optional[int] = None
    can_id_type: str = "STANDARD_CAN"
    canif_dlc: Optional[int] = None
    ecuc_pdu_length: Optional[int] = None
    tx_mode: str = ""
    cycle_time_ms: Optional[float] = None
    channel_name: str = ""
    signal_count: int = 0
    canif_pdu_name: str = ""
    canif_pdu_path: str = ""
    canif_handle_id: Optional[int] = None
    ecuc_lower_pdu_name: str = ""
    ecuc_lower_length: Optional[int] = None
    ecuc_upper_pdu_name: str = ""
    ecuc_upper_length: Optional[int] = None
    pdur_path_name: str = ""
    com_ipdu_name: str = ""
    com_ipdu_path: str = ""
    com_handle_id: Optional[int] = None
    cantp_nsdu_name: str = ""
    has_length_mismatch: bool = False
    has_broken_chain: bool = False
    primary_container_path: str = ""

    @property
    def can_id_hex(self) -> str:
        if self.can_id is None:
            return "-"
        is_ext = "EXTENDED" in (self.can_id_type or "").upper()
        return f"0x{self.can_id:08X}" if is_ext else f"0x{self.can_id:03X}"


@dataclass
class CommSignalRow:
    """Flattened ComSignal entry with resolved parent ComIPdu and bit-layout flags."""

    signal_name: str
    ipdu_name: str
    direction: str  # "TX" | "RX" | ""
    bit_position: Optional[int]
    bit_size: Optional[int]
    endianness: str = "BIG_ENDIAN"
    signal_type: str = "UINT8"
    init_value: str = "0"
    transfer_property: str = "PENDING"
    timeout_sec: Optional[float] = None
    handle_id: Optional[int] = None
    system_signal_ref: str = ""
    container_path: str = ""
    has_overlap: bool = False
    out_of_bounds: bool = False


@dataclass
class PduRRoutingRow:
    """Aggregated PduRRoutingPath row linking source and destination modules/PDUs."""

    path_name: str
    comm_type: str = "COMMUNICATION_INTERFACE"
    direction: str = ""
    src_module: str = ""
    src_pdu_name: str = ""
    src_handle_id: Optional[int] = None
    dest_module: str = ""
    dest_pdu_name: str = ""
    dest_handle_id: Optional[int] = None
    can_id_hex: str = "-"
    has_broken_ref: bool = False
    container_path: str = ""


@dataclass
class CommDiagnostic:
    """Structured cross-module communication diagnostic for Workbench & ProblemsView."""

    severity: str  # "error" | "warning" | "info"
    code: str
    message: str
    module_name: str
    container_path: str
    parameter_name: Optional[str] = None
    workbench_tab: int = 0
    suggested_fix: Optional[str] = None


@dataclass
class DbcSyncItem:
    """Single message entry inside a multi-module DBC derivation preview plan."""

    action: str  # "create" | "update" | "unchanged" | "skip"
    module_name: str
    direction: str  # "TX" | "RX" | "SKIP"
    category: str  # "COM" | "DIAG_TP" | "UNRELATED"
    message_name: str
    can_id: int
    can_id_hex: str
    is_extended: bool
    dlc: int
    cycle_time_ms: Optional[float]
    signal_count: int
    target_summary: str
    existing_canif_pdu: str = ""
    existing_com_ipdu: str = ""
    existing_pdur_path: str = ""
    existing_ecuc_lower_pdu: str = ""
    existing_ecuc_upper_pdu: str = ""
    message_obj: Any = field(default=None, repr=False)


@dataclass
class DbcSyncPlan:
    """Preview plan generated by :func:`plan_dbc_sync` before mutating ECUC modules."""

    dbc_path: Path
    db_name: str
    ecu_node: str
    channel_name: Optional[str]
    include_diag: bool
    update_existing: bool
    target_modules: List[str] = field(default_factory=list)
    missing_modules: List[str] = field(default_factory=list)
    items: List[DbcSyncItem] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)


@dataclass
class DbcSyncResult:
    """Mutation summary returned by :func:`apply_dbc_sync`."""

    created_ecuc_pdus: int = 0
    created_canif_pdus: int = 0
    updated_canif_pdus: int = 0
    created_pdur_paths: int = 0
    created_com_ipdus: int = 0
    updated_com_ipdus: int = 0
    created_com_signals: int = 0
    updated_com_signals: int = 0
    skipped_locked: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
