"""
ADS (armlink) scatter file generator

Writes a ``plan.Plan`` as a ``.scat`` file in the style of the vendor's ``LinkerAdsPf.scat``
(design.md D4):

* first line ``#! armclang --target=arm-arm-none-eabi -march=armv8-a -E -x c`` (the file is run
  through the C preprocessor, so comments are ``;`` lines without quotes or apostrophes);
* one ``#define <WINDOW>_ADDRESS 0x...`` per memory window that holds a region;
* one load region; the execution regions in plan order, the first of a window at the window's
  base, the others at ``AlignExpr(ImageLimit(<previous>), <align>)``;
* one ``*(.name)`` selector per output section, sections in name order;
* stack regions ``NAME start ALIGN 8 EMPTY 0x1000 {}``;
* the ``<NAME>_LIMIT AlignExpr(ImageLimit(NAME), <align>) EMPTY 0x0 {}`` regions together at the
  end of the load region, then the reserved regions of missing cores with a comment.

No time stamp: the same plan gives the same bytes.
"""
from typing import List

from ..plan import Plan, PlanRegion
from ..symbols import LIMIT_REGION_SUFFIX

FILE_NAME = "scatter.scat"
FIRST_LINE = "#! armclang --target=arm-arm-none-eabi -march=armv8-a -E -x c"
INDENT = "    "
DEFINE_WIDTH = 30


def _hex(value: int, width: int = 0) -> str:
    return f"0x{value:0{width}X}"


def _start(plan: Plan, region: PlanRegion) -> str:
    if region.start_window is not None:
        return plan.window(region.start_window).symbol
    return f"AlignExpr(ImageLimit({region.after}), {region.align})"


def _region_lines(plan: Plan, region: PlanRegion) -> List[str]:
    start = _start(plan, region)
    if region.empty:
        return [f"{INDENT}{region.name} {start} ALIGN {region.align} EMPTY {_hex(region.size)} {{}}"]
    lines = [f"{INDENT}{region.name} {start} ALIGN {region.align} {_hex(region.size)}", f"{INDENT}{{"]
    lines += [f"{INDENT * 2}*({section})" for section in region.sections]
    lines.append(f"{INDENT}}}")
    return lines


def generate(plan: Plan) -> str:
    """The scatter file text of ``plan``; ends with a newline, ``\\n`` line ends."""
    lines = [FIRST_LINE, "",
             "; Generated by the memory map tool of the AUTOSAR configurator.",
             f"; Source: {plan.source}" + (f", chip {plan.chip}" if plan.chip else ""),
             "; Do not edit by hand: the next generation replaces this file.",
             ""]
    for window in plan.windows:
        lines.append(f"#define {window.symbol.ljust(DEFINE_WIDTH)} {_hex(window.base, 8)}")
    lines.append("")
    for load in plan.load_regions:
        base = plan.window(load.window).symbol
        lines += [f"{load.name} {base} {_hex(load.size)}", "{"]
        window = None
        for region in (r for r in plan.regions if r.load_region == load.name):
            if region.window != window:
                if window is not None:
                    lines.append("")
                lines.append(f";{region.window}")
                window = region.window
            lines += _region_lines(plan, region)
        limits = [r for r in plan.regions if r.load_region == load.name and r.needs_limit]
        if limits:
            lines += ["", "; Limit regions: their Image$$<name>_LIMIT$$Base symbols mark where a region ends."]
            for region in limits:
                lines.append(f"{INDENT}{region.name}{LIMIT_REGION_SUFFIX} "
                             f"AlignExpr(ImageLimit({region.name}), {region.align}) EMPTY 0x0 {{}}")
        if plan.reserved:
            lines += ["",
                      "; Reserved regions for cores the chip does not have: code such as startup.c",
                      "; may refer to them by name, and the link needs them to exist. They take no",
                      "; sections. Switch the reserve option off when the startup code does not",
                      "; refer to them."]
            for reserved in plan.reserved:
                start = (f"AlignExpr(ImageLimit({reserved.after}), {reserved.align})"
                         if reserved.after else base)
                lines.append(f"{INDENT}{reserved.name} {start} EMPTY 0x0 {{}}")
                if reserved.needs_limit:
                    lines.append(f"{INDENT}{reserved.name}{LIMIT_REGION_SUFFIX} {start} EMPTY 0x0 {{}}")
        lines.append("}")
    return "\n".join(lines) + "\n"
