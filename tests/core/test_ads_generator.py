# --- registry -------------------------------------------------------------------------

def test_registry_lists_five_compilers_only_ads_supported():
    entries = gen.compilers()
    assert [e.key for e in entries] == [gen.ADS, gen.GHS, gen.HIGHTEC, gen.IAR, gen.TASKING]
    assert [e.key for e in entries if e.supported] == [gen.ADS]
    for entry in entries[1:]:
        assert entry.reason.startswith(gen.NOT_YET)


@pytest.mark.parametrize("key", [gen.GHS, gen.HIGHTEC, gen.IAR, gen.TASKING])
def test_unsupported_compiler_raises_and_gives_no_text(key):
    with pytest.raises(gen.UnsupportedCompiler, match=gen.NOT_YET):
        gen.generate(key, _plan())


def test_unknown_compiler_raises():
    with pytest.raises(gen.UnsupportedCompiler):
        gen.generate("keil", _plan())


def test_ads_through_the_registry():
    out = gen.generate(gen.ADS, _plan())
    assert (out.file_name, out.directory) == ("scatter.scat", "Ads")
    assert out.text == ads.generate(_plan())


# --- output -------------------------------------------------------------------------------

def test_output_line_by_line():
    assert ads.generate(_plan()).splitlines() == EXPECTED.splitlines()
    assert ads.generate(_plan()) == EXPECTED


def test_first_line_and_no_time_stamp():
    text = ads.generate(_plan())
    assert text.split("\n", 1)[0] == ads.FIRST_LINE
    assert not re.search(r"\d{4}[-/]\d{2}[-/]\d{2}|\d{2}:\d{2}", text)


def test_spec_region_start_follows_previous():
    text = ads.generate(_plan())
    assert "PRIVATE_BSS_CORE0 AlignExpr(ImageLimit(PRIVATE_DATA_CORE0), 64) ALIGN 64" in text


def test_reserved_option_off_writes_no_reserved_region():
    config = _config()
    pl.set_reserve_missing_cores(config, False)
    text = ads.generate(_plan(config))
    assert "PRIVATE_DATA_CORE2" not in text and "Reserved regions" not in text


def test_no_limit_section_when_nothing_needs_one():
    config = _config()
    plan = pl.build_plan(config, ROWS, CHIP, [n for n in NEEDS if n.region == "CORE0_USER_STACK"])
    text = ads.generate(plan)
    assert "_LIMIT" not in text.replace("_LIMIT$$Base", "")


def test_byte_for_byte_determinism():
    first = ads.generate(_plan()).encode("utf-8")
    second = ads.generate(_plan()).encode("utf-8")
    assert hashlib.sha256(first).hexdigest() == hashlib.sha256(second).hexdigest()


# --- round trip -----------------------------------------------------------------------------

def _round_trip(plan):
    scatter = parse_scatter(ads.generate(plan), "scatter.scat")
    expected = [r.name for r in plan.regions]
    expected += [n + "_LIMIT" for n in [r.name for r in plan.regions if r.needs_limit]]
    for r in plan.reserved:
        expected.append(r.name)
        if r.needs_limit:
            expected.append(r.name + "_LIMIT")
    assert [r.name for r in scatter.regions] == expected
    for region in plan.regions:
        read = scatter.region(region.name)
        assert read.load_region == "ROM_CODE"
        assert [s.names for s in read.selectors] == [(name,) for name in region.sections]
        assert all(s.files == "*" and not s.attributes for s in read.selectors)
        window = plan.window(region.window)
        if region.start_window:
            assert read.address == window.base
        else:
            assert read.follows == region.after and read.address == window.base
    return scatter


def test_round_trip_small_plan():
    _round_trip(_plan())


def test_full_tha6206_plan_from_the_factory_data():
    factory = fy.load_factory("THA6206_LFBGA292")
    chip = ChipDatabase(default_chips_dir()).get_chip("THA6206_LFBGA292")
    config = pl.MemoryMapConfig(chip="THA6206_LFBGA292", regions=fy.factory_regions(factory),
                                rules=list(factory.rules),
                                trimmed=["CORE2_USER_STACK", "PRIVATE_DATA_CORE2"])
    plan = pl.build_plan(config, ROWS, chip.memory_regions, [], factory.layout)
    refusals, _ = pl.check_plan(plan)
    assert refusals == []
    assert {r.name for r in plan.regions} == {e["name"] for e in factory.layout}
    scatter = _round_trip(plan)
    names = {r.name for r in scatter.regions}
    assert {e["name"] for e in factory.layout} <= names
    assert {"CORE2_USER_STACK", "PRIVATE_DATA_CORE2"} <= names
    assert plan.region("INT_VECTOR_TABLE").start_window == "CPUXPFLASH0"
    assert plan.region("EX_CODE").after == "INT_VECTOR_TABLE"
    assert plan.region("CORE0_USER_STACK").size == 0x1000
    assert ads.generate(plan) == ads.generate(pl.build_plan(config, ROWS, chip.memory_regions, [],
                                                            factory.layout))
